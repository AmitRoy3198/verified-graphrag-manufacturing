"""Phase 5: build every results table from the files in results/.

The README tables are copied from results/summary.md, which this script writes,
so no number is typed by hand. tests/test_readme_numbers.py checks that every
number in a README table exists in a results JSON file.
Run:  python -m src.report
"""
import json

from src.config import RESULTS


def load(name):
    return json.loads((RESULTS / name).read_text(encoding="utf-8"))


def table(header, rows):
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(lines)


def phase1():
    s = load("phase1_schema.json")
    o, sh = s["ontology"], s["shapes"]
    return table(["Classes", "Object properties", "Datatype properties", "Node shapes", "Property shapes", "Constraints"],
                 [[o["classes"], o["object_properties"], o["datatype_properties"],
                   sh["node_shapes"], sh["property_shapes"], sh["constraints_total"]]])


def phase2():
    rows = []
    for label, f in [("v1: optional JSON fields", "phase2_v1_scores.json"),
                     ("v2: all fields required, output cap", "phase2_scores.json")]:
        o = load(f)["overall"]
        rows.append([label, o["precision"], o["recall"], o["f1"], o["correct"], o["extracted"], o["gold"], f"`results/{f}`"])
    return table(["Extraction run", "Precision", "Recall", "F1", "Correct", "Extracted", "Gold", "Source"], rows)


def phase3(name):
    r = load(name)
    has_accept = "accepted_repairs" in r["rounds"][-1]
    header = ["Round"] + (["Accepted repairs"] if has_accept else []) + \
             ["Violations", "Entities w/ violations", "Triples", "Precision", "Recall", "F1"]
    rows = []
    for x in r["rounds"]:
        row = [x["round"]] + ([x.get("accepted_repairs", "-")] if has_accept else [])
        rows.append(row + [x["violations"], x["entities_with_violations"], x["triples"],
                           x["precision"], x["recall"], x["f1"]])
    return table(header, rows)


def per_predicate():
    before = load("phase2_scores.json")["per_predicate"]
    after = load("phase3_v2_repair.json")["final_per_predicate"]
    rows = [[k, before[k]["f1"], after.get(k, {}).get("f1", "-"), before[k]["gold"]] for k in before]
    return table(["Predicate", "F1 before repair", "F1 after v2 repair", "Gold triples"], rows)


NAMES = {"vector_rag": "Vector RAG (raw documents)",
         "graphrag_unrepaired": "GraphRAG, unrepaired graph",
         "graphrag_repaired": "GraphRAG, repaired graph (v2)",
         "graphrag_gold": "GraphRAG, ground-truth graph (upper bound)"}


def phase4(name="phase4_scores.json"):
    s = load(name)
    rows = []
    for c, label in NAMES.items():
        v = s[c]
        pt = v["per_type"]
        rows.append([label, v["exact"], v["lenient"]] +
                    [f"{pt[t]['exact']} / {pt[t]['lenient']}" for t in ["1-hop", "multi-hop", "aggregation"]])
    return table(["Condition", "Exact", "Lenient", "1-hop (10) exact / lenient", "Multi-hop (8)", "Aggregation (7)"], rows)


def paired():
    s = load("phase4_scores.json")["paired_comparisons_lenient"]
    rows = []
    for pair, v in s.items():
        a, b = pair.split(" vs ")
        rows.append([f"{NAMES[a]} vs {NAMES[b]}", v["both_right"], v[f"only_{a}"], v[f"only_{b}"],
                     v["both_wrong"], v["sign_test_p"]])
    return table(["A vs B (lenient)", "Both right", "Only A", "Only B", "Both wrong", "Sign test p"], rows)


def llm_usage():
    """Number of LLM calls and LLM time per phase, from results/llm_log.jsonl -> results/llm_usage.json."""
    usage = {}
    for line in (RESULTS / "llm_log.jsonl").read_text(encoding="utf-8").splitlines():
        r = json.loads(line)
        u = usage.setdefault(r["phase"], {"calls": 0, "hours": 0.0})
        u["calls"] += 1
        u["hours"] += r["seconds"] / 3600
    for u in usage.values():
        u["hours"] = round(u["hours"], 2)
    total = {"calls": sum(u["calls"] for u in usage.values()), "hours": round(sum(u["hours"] for u in usage.values()), 2)}
    (RESULTS / "llm_usage.json").write_text(json.dumps({"per_phase": usage, "total": total}, indent=2), encoding="utf-8")
    rows = [[p, u["calls"], u["hours"]] for p, u in usage.items()] + [["total", total["calls"], total["hours"]]]
    return table(["Phase (log label)", "LLM calls", "LLM hours"], rows)


def main():
    v1, v2 = load("phase3_v1_repair.json"), load("phase3_v2_repair.json")
    parts = [
        "# Results summary (generated by `python -m src.report`)",
        "## Phase 1: schema (`results/phase1_schema.json`)", phase1(),
        "## Phase 2: extraction", phase2(),
        "## Phase 3 v1: full-rewrite repair (`results/phase3_v1_repair.json`)", phase3("phase3_v1_repair.json"),
        f"Repair calls: {len(v1['repairs'])}",
        "## Phase 3 v2: targeted + gated repair (`results/phase3_v2_repair.json`)", phase3("phase3_v2_repair.json"),
        f"Attempts: {v2['attempts']}, accepted: {v2['accepted']}, deleted entities: {v2['deleted_entities']}",
        "## Per-predicate F1, before and after v2 repair", per_predicate(),
        "## Phase 4 v2: question answering (`results/phase4_scores.json`)", phase4(),
        "## Phase 4 v1 (harness bug, kept for the record: `results/phase4_v1_scores.json`)", phase4("phase4_v1_scores.json"),
        "## Phase 4: paired comparison", paired(),
        "## LLM usage (`results/llm_usage.json`)", llm_usage(),
    ]
    text = "\n\n".join(parts) + "\n"
    (RESULTS / "summary.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
